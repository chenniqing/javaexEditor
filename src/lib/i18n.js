export const defaultLocales = {
  "zh-CN": zhCN,
  zh: zhCN,
  "en-US": enUS,
  en: enUS
};

function isPlainObject(value) {
  return Object.prototype.toString.call(value) === "[object Object]";
}

export function mergeLocaleMessages(...sources) {
  const result = {};
  sources.forEach((source) => {
    if (!isPlainObject(source)) {
      return;
    }
    Object.entries(source).forEach(([key, value]) => {
      if (isPlainObject(value) && isPlainObject(result[key])) {
        result[key] = mergeLocaleMessages(result[key], value);
      } else if (isPlainObject(value)) {
        result[key] = mergeLocaleMessages(value);
      } else {
        result[key] = value;
      }
    });
  });
  return result;
}

export function resolveLocaleConfig(locale = "zh-CN", locales = {}, messages = {}) {
  const localeObject = isPlainObject(locale) ? locale : null;
  const name = localeObject?.name || localeObject?.locale || (typeof locale === "string" ? locale : "zh-CN");
  const baseMessages = defaultLocales[name] || locales[name] || zhCN;
  const namedMessages = locales[name] || {};
  const inlineMessages = localeObject?.messages || localeObject?.message || {};
  return {
    name,
    messages: mergeLocaleMessages(zhCN, baseMessages, namedMessages, messages, inlineMessages)
  };
}

export function getLocaleValue(messages, path, fallback = "") {
  const value = String(path || "").split(".").reduce((source, key) => {
    if (source == null) {
      return undefined;
    }
    return source[key];
  }, messages);
  return value == null ? fallback : value;
}

export function formatLocaleText(template, payload = {}) {
  return String(template || "").replace(/\{\{\s*(\w+)\s*\}\}/g, (_, key) => {
    const value = payload[key];
    return value == null ? "" : String(value);
  });
}
